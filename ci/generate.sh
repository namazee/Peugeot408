#!/usr/bin/env bash
# Installs XcodeGen, writes Config/Secrets.xcconfig from env, generates the project and resolves packages.
set -euo pipefail

command -v xcodegen >/dev/null || brew install xcodegen

# Shared theme (theme/tokens.json) must match the generated Swift constants.
python3 tools/gen-theme.py --check

# Secrets.xcconfig from environment (empty values are fine).
{
  echo "// Generated by CI. Do not commit."
  echo "AQI_API_KEY = ${AQI_API_KEY:-}"
} > Config/Secrets.xcconfig

xcodegen generate
xcodebuild -resolvePackageDependencies -project Peugeot408.xcodeproj -scheme Peugeot408
