"""Writes CarKit/Theme/ThemeTokens.swift from theme/tokens.json (the shared theme, spec §7).

    python3 tools/gen-theme.py           # regenerate
    python3 tools/gen-theme.py --check   # CI: fail if the Swift file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "theme" / "tokens.json"
OUT = ROOT / "CarKit" / "Theme" / "ThemeTokens.swift"


def hex_literal(value):
    value = value.lstrip("#")
    if len(value) != 6:
        raise SystemExit(f"Bad colour {value!r} in {TOKENS}")
    return "0x" + value.upper()


def render():
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    lines = [
        "// Generated by tools/gen-theme.py from theme/tokens.json. Do not edit; edit the JSON and re-run.",
        "// Remotion reads the same JSON, so the app and the videos share one palette (spec §7).",
        "",
        "public enum ThemeTokens {",
    ]
    for group in ("colors", "aqi"):
        prefix = "" if group == "colors" else "aqi"
        for name, value in tokens[group].items():
            if name.startswith("$"):
                continue
            swift_name = name if not prefix else prefix + name[0].upper() + name[1:]
            lines.append(f"    public static let {swift_name}: UInt32 = {hex_literal(value)}")
    for name, value in tokens["radius"].items():
        lines.append(f"    public static let {name}Radius: Double = {float(value)}")
    lines.append("}")
    return "\n".join(lines) + "\n"


text = render()
if "--check" in sys.argv:
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current.replace("\r\n", "\n") != text:
        print(f"{OUT.relative_to(ROOT)} is out of date with theme/tokens.json. Run: python3 tools/gen-theme.py")
        sys.exit(1)
    print("Theme tokens: Swift file is up to date.")
else:
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}")
